"""
Fetch andreiastra's iNaturalist observations at a specific dive site (or all sites)
and write a Markdown report with a thumbnail for each observation to OUTPUT/<site>.md.

An observation belongs to the site when its place_guess resolves to the canonical site
via the keyword list in site_names.py, or when its GPS position is within
CLUSTER_RADIUS_M of the centroid of those matches (catches observations logged
under a generic place name such as "Cork, Co. Cork, Ireland").

Usage:
  .venv/bin/python scripts/site_observations.py "Bank Pier"
  .venv/bin/python scripts/site_observations.py "Kilcrohane Pier"
  .venv/bin/python scripts/site_observations.py --all
"""
import argparse
import collections
import os
import re
import sys
from datetime import date

sys.path.insert(0, os.path.dirname(__file__))
from config import CLUSTER_RADIUS_M, OUTPUT_DIR, USER_ID
from generate_location_ratings import fetch_all_observations, haversine, photo_md
from site_names import SITE_KEYWORDS
from species_classification import species_type

_ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
SITES_FILE = os.path.join(_ROOT, "Preferred_dive_site_names_ireland.txt")


def load_canonical_sites():
    """Load canonical dive site names from Preferred_dive_site_names_ireland.txt."""
    sites = []
    if os.path.exists(SITES_FILE):
        with open(SITES_FILE, encoding="utf-8") as f:
            for line in f:
                name = line.strip()
                if name:
                    sites.append(name)
    return sites


def resolve_canonical_name(query, canonical_sites):
    """
    Resolve a user-provided string to a canonical dive site name.
    Checks exact matches, keyword mappings in site_names.py, and substring matches.
    """
    q_lower = query.strip().lower()
    if not q_lower:
        return None

    # 1. Exact canonical name match (case-insensitive)
    for site in canonical_sites:
        if site.lower() == q_lower:
            return site

    # 2. Match against SITE_KEYWORDS
    for kw, site_name in SITE_KEYWORDS:
        if kw == q_lower or kw in q_lower or q_lower in kw:
            if site_name in canonical_sites or not canonical_sites:
                return site_name

    # 3. Substring match against canonical site names
    matches = [s for s in canonical_sites if q_lower in s.lower()]
    if len(matches) == 1:
        return matches[0]
    elif len(matches) > 1:
        # Prefer shortest or exact prefix
        for s in matches:
            if s.lower().startswith(q_lower):
                return s
        return matches[0]

    return query.strip()


def slugify_site_name(site_name):
    """Generate a clean snake_case filename slug for a site name."""
    # Special-case Kilcrohane Pier -> kilcrohane for backwards compatibility if desired, or kilcrohane_pier
    slug = re.sub(r"[^a-z0-9]+", "_", site_name.lower()).strip("_")
    return slug


def named_at_site(obs, canonical_site):
    guess = (obs.get("place_guess") or "").lower()
    return any(name == canonical_site and keyword in guess for keyword, name in SITE_KEYWORDS)


def coords(obs):
    c = (obs.get("geojson") or {}).get("coordinates")
    return (c[1], c[0]) if c else None


def at_site(observations, canonical_site):
    """Observations named for the site, plus any within CLUSTER_RADIUS_M of it."""
    named = [o for o in observations if named_at_site(o, canonical_site)]
    points = [p for p in map(coords, named) if p]
    if not points:
        return named
    lat = sum(p[0] for p in points) / len(points)
    lon = sum(p[1] for p in points) / len(points)
    return [
        o for o in observations
        if o in named or (coords(o) and haversine(lat, lon, *coords(o)) <= CLUSTER_RADIUS_M)
    ]


def obs_url(obs):
    return obs.get("uri") or f"https://www.inaturalist.org/observations/{obs['id']}"


def names(obs):
    taxon = obs.get("taxon") or {}
    sci = taxon.get("name") or ""
    return taxon.get("preferred_common_name") or sci or "Unidentified", sci


def render(obs_list, site_name, notes=None):
    if notes is None:
        notes = []
    research = sum(1 for o in obs_list if o.get("quality_grade") == "research")
    dives = {o.get("observed_on") for o in obs_list if o.get("observed_on")}
    species = collections.Counter((names(o)[0], names(o)[1], species_type(o)) for o in obs_list)

    lines = [
        f"# Observations at {site_name}\n",
        f"> Generated by `scripts/site_observations.py` on {date.today()} "
        f"from live iNaturalist data for `{USER_ID}`.\n",
    ]
    lines += [f"> ⚠️ {n}" for n in notes]
    lines += [
        f"\n**{len(obs_list)}** observations · **{len(species)}** taxa · "
        f"**{len(dives)}** dates · **{research}** Research Grade, "
        f"**{len(obs_list) - research}** need ID\n",
        "## Species\n",
        "| Species | Organism Type | Observations |",
        "|---|---|---:|",
    ]
    for (common, sci, org_type), count in sorted(species.items(), key=lambda kv: (-kv[1], kv[0][0].lower())):
        label = f"**{common}**" + (f" (*{sci}*)" if sci and sci != common else "")
        lines.append(f"| {label} | {org_type} | {count} |")

    lines += [
        "\n## Observations\n",
        "| Photo | Date | Species | Organism Type |",
        "|---|---|---|---|",
    ]
    for obs in sorted(obs_list, key=lambda o: o.get("observed_on") or "", reverse=True):
        common, sci = names(obs)
        org_type = species_type(obs)
        label = f"[{common}]({obs_url(obs)})" + (f" (*{sci}*) " if sci and sci != common else "")
        # note: match original formatting for label
        if sci and sci != common:
            label = f"[{common}]({obs_url(obs)}) (*{sci}*)"
        else:
            label = f"[{common}]({obs_url(obs)})"
        lines.append(f"| {photo_md(obs)} | {obs.get('observed_on') or '—'} | {label} | {org_type} |")

    return "\n".join(lines) + "\n"


def generate_site_report(site_query, observations=None, notes=None, output_path=None):
    """
    Generate a markdown report for a given site.
    Returns (canonical_site, matches, content, output_file).
    """
    if notes is None:
        notes = []
    canonical_sites = load_canonical_sites()
    canonical_site = resolve_canonical_name(site_query, canonical_sites)

    if observations is None:
        observations = fetch_all_observations(notes)

    matches = at_site(observations, canonical_site)
    if not matches:
        return canonical_site, [], None, None

    if output_path is None:
        slug = slugify_site_name(canonical_site)
        output_file = os.path.join(OUTPUT_DIR, f"{slug}.md")
    else:
        output_file = output_path

    content = render(matches, canonical_site, notes)
    os.makedirs(os.path.dirname(os.path.abspath(output_file)), exist_ok=True)
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(content)

    return canonical_site, matches, content, output_file


def main():
    parser = argparse.ArgumentParser(
        description="Generate iNaturalist observations report for dive sites in West Cork."
    )
    parser.add_argument(
        "site",
        nargs="?",
        default=None,
        help="Site name or keyword (e.g., 'Bank Pier', 'Kilcrohane', 'Canty').",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="Generate reports for all canonical dive sites with observations.",
    )
    parser.add_argument(
        "--output",
        "-o",
        default=None,
        help="Custom output file path.",
    )
    args = parser.parse_args()

    if not args.site and not args.all:
        parser.print_help()
        print("\nAvailable canonical dive sites:")
        for s in load_canonical_sites():
            print(f"  - {s}")
        return

    notes = []
    observations = fetch_all_observations(notes)

    if args.all:
        canonical_sites = load_canonical_sites()
        count = 0
        for site in canonical_sites:
            c_site, matches, content, out = generate_site_report(
                site, observations=observations, notes=notes
            )
            if matches:
                count += 1
                print(f"[{c_site}] Saved {len(matches)} observations → {os.path.normpath(out)}")
        print(f"\nGenerated reports for {count} sites.")
    else:
        c_site, matches, content, out = generate_site_report(
            args.site, observations=observations, notes=notes, output_path=args.output
        )
        if not matches:
            print(f"No observations found for '{args.site}' (resolved to '{c_site}').")
            return
        print(f"Saved {len(matches)} of {len(observations)} observations for '{c_site}' → {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
