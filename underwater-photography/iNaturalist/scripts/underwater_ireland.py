"""
Write a Markdown report of andreiastra's underwater observations in Ireland,
grouped by dive site, to OUTPUT/underwater_ireland.md.

Reuses generate_location_ratings (fetching, clustering, site resolution and
per-site rendering). Underwater means the observation clusters onto a dive site
in Preferred_dive_site_names_ireland.txt; sites outside Ireland are dropped.

Obscured observations are listed separately. iNaturalist hides the true
location of threatened species (e.g. IUCN VU) from the public API and returns a
randomised point instead (public accuracy can be 25 km or more). Such a point
cannot be matched to a dive site, so these observations are excluded from the
site sections and listed in their own "Obscured locations" section, with their
IUCN status. Place them by hand: the owner sees the true location on iNaturalist.

Usage:
  .venv/bin/python scripts/underwater_ireland.py
"""
import os
import sys
from datetime import date

sys.path.insert(0, os.path.dirname(__file__))
from config import OUTPUT_DIR, USER_ID
from generate_location_ratings import (
    SITES_FILE,
    cluster_and_label,
    count_dives_per_site,
    fetch_all_observations,
    load_dive_sites,
    photo_md,
    render_site_section,
    species_per_site,
)
from site_names import IGNORED_KEYWORDS
from site_observations import names, obs_url

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "underwater_ireland.md")

# Dive sites in the preferred list that are not in Ireland.
NON_IRELAND_SITES = {"Scapa Flow"}


def anchor(site):
    # Same anchor format that render_site_section() emits.
    return site.lower().replace(" ", "-").replace("'", "").replace("(", "").replace(")", "")


def split_obscured(observations):
    """Return (visible, obscured). Obscured excludes ignored (non-dive) places, e.g. Egypt."""
    visible, obscured = [], []
    for obs in observations:
        if not obs.get("obscured"):
            visible.append(obs)
            continue
        guess = (obs.get("place_guess") or "").lower()
        if not any(kw in guess for kw in IGNORED_KEYWORDS):
            obscured.append(obs)
    return visible, obscured


def iucn_status(obs):
    """IUCN category in upper case (e.g. 'VU'), or '—' when the taxon has none."""
    status = (obs.get("taxon") or {}).get("conservation_status") or {}
    return status["status"].upper() if status.get("status") else "—"


def render_obscured(obscured):
    # Vulnerable and worse first, then by date (newest first).
    order = {"CR": 0, "EN": 1, "VU": 2, "NT": 3}
    ranked = sorted(obscured, key=lambda o: o.get("observed_on") or "", reverse=True)
    ranked.sort(key=lambda o: order.get(iucn_status(o), 9))
    lines = [
        "## Obscured locations\n",
        "iNaturalist hides the true location of these observations (threatened species), "
        "so they can't be matched to a dive site. Check the location on iNaturalist while "
        "logged in.\n",
        "| Photo | Species | Date | IUCN | Place on iNaturalist |",
        "|---|---|---|---|---|",
    ]
    for obs in ranked:
        common, sci = names(obs)
        label = f"[{common}]({obs_url(obs)})" + (f" (*{sci}*)" if sci and sci != common else "")
        lines.append(
            f"| {photo_md(obs)} | {label} | {obs.get('observed_on') or '—'} "
            f"| {iucn_status(obs)} | {obs.get('place_guess') or '—'} |"
        )
    return "\n".join(lines)


def underwater_observations(notes):
    """Return ({site: [obs]}, [obscured obs]) for the user's underwater observations in Ireland."""
    observations = fetch_all_observations(notes)
    visible, obscured = split_obscured(observations)
    site_obs = cluster_and_label(visible, load_dive_sites(SITES_FILE), notes)
    site_obs = {s: o for s, o in site_obs.items() if s not in NON_IRELAND_SITES}
    return site_obs, obscured


def main():
    notes = []
    site_obs, obscured = underwater_observations(notes)
    dives = count_dives_per_site(site_obs)
    species = species_per_site(site_obs)

    # Most observations first, then most dives, then alphabetical.
    ranked = sorted(site_obs, key=lambda s: (-len(site_obs[s]), -dives[s], s))
    total = sum(len(o) for o in site_obs.values())

    lines = [
        "# Underwater observations in Ireland\n",
        f"> Generated by `scripts/underwater_ireland.py` on {date.today()} "
        f"from live iNaturalist data for `{USER_ID}`.\n",
    ]
    lines += [f"> ⚠️ {n}" for n in notes]
    lines += [
        f"\n**{total}** observations · **{len(ranked)}** sites · "
        f"**{len(obscured)}** with obscured location (listed separately)\n",
        "## Sites\n",
        "| Site | Dates | Observations | Species |",
        "|---|---:|---:|---:|",
    ]
    for site in ranked:
        lines.append(
            f"| [{site}](#{anchor(site)}) | {dives[site]} | {len(site_obs[site])} | {len(species[site])} |"
        )
    lines.append("\n---\n")
    if obscured:
        lines.append(render_obscured(obscured))
        lines.append("\n---\n")
    for site in ranked:
        lines.append(render_site_section(site, site_obs[site], dives[site], species[site]))
        lines.append("\n---\n")

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Saved {total} observations at {len(ranked)} sites → {os.path.normpath(OUTPUT_FILE)}")
    print(f"{len(obscured)} observation(s) with obscured location listed separately.")
    for note in notes:
        print(f"WARNING: {note}")


if __name__ == "__main__":
    main()
