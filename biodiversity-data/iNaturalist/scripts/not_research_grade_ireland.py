"""
Write reports/not_research_grade_ireland.md: andreiastra's underwater observations
in Ireland that are not Research Grade yet (Needs ID), grouped by organism type
(Fish, Crab, Nudibranch, Anemone, ...) as classified by species_classification.species_type().

Same observations as the other underwater reports (underwater_stats.underwater_entries()).
Observations with an obscured location are included, with "Obscured location" as site
(see README "Obscured locations").

Usage:
  ../.venv/bin/python scripts/not_research_grade_ireland.py
"""
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(__file__))
from config import OUTPUT_DIR, USER_ID
from generate_location_ratings import photo_md
from species_classification import names, obs_url, species_type
from underwater_stats import site_label, underwater_entries

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "not_research_grade_ireland.md")


def anchor(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def row(site, obs):
    common, sci = names(obs)
    label = f"[**{common}**" + (f"<br>*{sci}*" if sci and sci != common else "") + f"]({obs_url(obs)})"
    return f"| {photo_md(obs)} | {label} | {site_label(site)} | {obs.get('observed_on') or '—'} |"


def main():
    notes = []
    entries = underwater_entries(notes)
    pending = [(s, o) for s, o in entries if o.get("quality_grade") != "research"]

    by_type = defaultdict(list)
    for site, obs in pending:
        by_type[species_type(obs)].append((site, obs))
    # Most observations first, then alphabetical. Within a type: by species, newest first.
    ranked = sorted(by_type, key=lambda t: (-len(by_type[t]), t))
    for items in by_type.values():
        items.sort(key=lambda e: e[1].get("observed_on") or "", reverse=True)
        items.sort(key=lambda e: names(e[1])[0].lower())

    lines = [
        "# Underwater observations in Ireland that are not Research Grade yet\n",
        f"> Generated by `scripts/not_research_grade_ireland.py` "
        f"from live iNaturalist data for `{USER_ID}`.\n",
    ]
    lines += [f"> ⚠️ {n}" for n in notes]
    lines += [
        f"\n**{len(pending)}** of **{len(entries)}** observations still need an ID, "
        f"grouped by organism type. Full list per site: [`underwater_ireland.md`](underwater_ireland.md).\n",
        "## Organism types\n",
        "| Type | Needs ID | Taxa |",
        "|---|---:|---:|",
    ]
    for t in ranked:
        taxa = {names(o) for _, o in by_type[t]}
        lines.append(f"| [{t}](#{anchor(t)}) | {len(by_type[t])} | {len(taxa)} |")
    lines.append("\n---\n")

    for t in ranked:
        lines += [
            f'\n<a id="{anchor(t)}"></a>',
            f"## {t}\n",
            f"**Needs ID:** {len(by_type[t])}\n",
            "| Photo | Species | Site | Date |",
            "|-------|---------|------|------|",
        ]
        lines += [row(site, obs) for site, obs in by_type[t]]
        lines.append("\n---\n")

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Saved {len(pending)} observations in {len(ranked)} organism types → {os.path.normpath(OUTPUT_FILE)}")
    for note in notes:
        print(f"WARNING: {note}")


if __name__ == "__main__":
    main()
