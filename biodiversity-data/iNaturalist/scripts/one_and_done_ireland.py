"""
Write reports/one_and_done_ireland.md: the underwater species in Ireland that
andreiastra has recorded only once.

"Once" means exactly one observation identified to species rank. These are the
species most worth looking for again: the report groups them by the site where
they were seen, with the grade (a Needs ID one-off may not even be the species
you think it is) and the type of organism.

Observations with an obscured location are listed under "Obscured location"
(see README "Obscured locations").

Usage:
  ../.venv/bin/python scripts/one_and_done_ireland.py
"""
import os
import sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(__file__))
from config import OUTPUT_DIR, USER_ID
from generate_location_ratings import photo_md
from species_classification import species_type
from underwater_stats import pct, site_label, species_table, taxon_link, underwater_entries

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "one_and_done_ireland.md")


def render(table, notes):
    once = {tid: i for tid, i in table.items() if len(i["entries"]) == 1}
    grades = Counter(i["entries"][0][1].get("quality_grade") for i in once.values())

    by_site = defaultdict(list)
    for info in once.values():
        site, obs = info["entries"][0]
        by_site[site_label(site)].append((info, obs))

    # Species seen more than once, by number of sightings, to show the other end.
    repeat = Counter(len(i["entries"]) for i in table.values() if len(i["entries"]) > 1)

    lines = [
        "# One-and-done: underwater species seen only once in Ireland\n",
        f"> Generated by `scripts/one_and_done_ireland.py` "
        f"from live iNaturalist data for `{USER_ID}`. Species rank only; observations "
        f"identified to genus or higher are not counted.\n",
    ]
    lines += [f"> ⚠️ {n}" for n in notes]
    lines += [
        f"\n**{len(once)}** of **{len(table)}** species ({pct(len(once), len(table))}) were "
        f"recorded in exactly one observation · **{grades['research']}** Research Grade, "
        f"**{grades['needs_id']}** Needs ID.\n",
        "A high share is what a new life list looks like: every dive still turns up "
        "species you haven't seen before. It also means most of the list rests on a single "
        "photo. These are the species to look for on the next dive at the same site.\n",
        "## How often each species was seen\n",
        "| Observations | Species |",
        "|--:|--:|",
        f"| 1 | {len(once)} |",
    ]
    for n in sorted(repeat):
        lines.append(f"| {n} | {repeat[n]} |")

    lines += ["\n## By organism type\n", "| Type | Seen once | All species | Share once |", "|---|--:|--:|--:|"]
    totals = Counter(species_type(i["entries"][0][1]) for i in table.values())
    seen_once = Counter(species_type(i["entries"][0][1]) for i in once.values())
    for kind, total in sorted(totals.items(), key=lambda kv: (-seen_once[kv[0]], kv[0])):
        lines.append(f"| {kind} | {seen_once[kind]} | {total} | {pct(seen_once[kind], total)} |")

    ranked_sites = sorted(by_site.items(), key=lambda kv: (-len(kv[1]), kv[0]))
    lines += ["\n## By site\n", "| Site | Seen once |", "|---|--:|"]
    lines += [f"| [{s}](#{s.lower().replace(' ', '-').replace(chr(39), '')}) | {len(v)} |"
              for s, v in ranked_sites]

    for site, items in ranked_sites:
        items.sort(key=lambda it: it[1].get("observed_on") or "")
        lines += [f"\n## {site}\n", "| Photo | Species | Type | Date | Grade |", "|---|---|---|---|---|"]
        for info, obs in items:
            grade = "✅ Research Grade" if obs.get("quality_grade") == "research" else "🔍 Needs ID"
            lines.append(
                f"| {photo_md(obs)} | {taxon_link(info['taxon'])} | {species_type(obs)} "
                f"| {obs.get('observed_on') or '—'} | {grade} |"
            )
    return "\n".join(lines) + "\n"


def main():
    notes = []
    table = species_table(underwater_entries(notes))
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(render(table, notes))
    once = sum(1 for i in table.values() if len(i["entries"]) == 1)
    print(f"Saved {once} one-and-done species of {len(table)} → {os.path.normpath(OUTPUT_FILE)}")
    for note in notes:
        print(f"WARNING: {note}")


if __name__ == "__main__":
    main()
