"""
Write reports/cork_species.md: every species other iNaturalist observers have recorded
in Co Cork (Research Grade, same land and seaweed exclusions as gap_analysis_ireland.py),
with the ones andreiastra has recorded underwater in Ireland marked.

One request per page of results:
  GET /v1/observations/species_counts?place_id=<CORK_PLACE_ID>&quality_grade=research
        &without_taxon_id=<LAND_TAXON_IDS + SEAWEED_TAXON_IDS>

A species is "observed" when it is on your underwater list at species rank (any grade, any
Irish dive site), the same test as gap_analysis_ireland.py. Species-rank taxa only.
The Observations column links to the Research Grade records in Co Cork on iNaturalist.

Caveats:
  * Co Cork is a county polygon, so shore and intertidal records are included, as in the
    gap analysis. Counts are observations, not dives.
  * Marine mammals and seabirds are excluded (LAND_TAXON_IDS), and so are brown seaweeds.

Usage:
  .venv/bin/python scripts/cork_species.py
"""
import os
import sys
import time
from collections import defaultdict

import requests

sys.path.insert(0, os.path.dirname(__file__))
from config import API_BASE, CORK_PLACE_ID, OUTPUT_DIR, THROTTLE_S, USER_ID
from gap_analysis_ireland import EXCLUDED_TAXA, PER_PAGE, label, thumb
from species_classification import species_type
from underwater_stats import species_table, underwater_entries

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "cork_species.md")


def fetch_cork_species():
    """Species recorded in Co Cork: [{id, name, common, type, count, photo}]."""
    results, page, total, seen = [], 1, None, 0
    while total is None or seen < total:
        r = requests.get(f"{API_BASE}/observations/species_counts", params={
            "place_id": CORK_PLACE_ID, "quality_grade": "research", "locale": "en",
            "without_taxon_id": EXCLUDED_TAXA, "per_page": PER_PAGE, "page": page,
        }, timeout=30)
        r.raise_for_status()
        data = r.json()
        total = data.get("total_results", 0)
        batch = data.get("results", [])
        if not batch:
            break
        seen += len(batch)
        for item in batch:
            t = item["taxon"]
            if t.get("rank") != "species":
                continue
            results.append({
                "id": t["id"], "name": t.get("name"), "common": t.get("preferred_common_name"),
                "type": species_type({"taxon": t}),
                "count": item["count"], "photo": (t.get("default_photo") or {}).get("square_url"),
            })
        page += 1
        time.sleep(THROTTLE_S)
    return results


def obs_link(sp):
    url = (f"https://www.inaturalist.org/observations?place_id={CORK_PLACE_ID}"
           f"&taxon_id={sp['id']}&quality_grade=research&verifiable=true")
    return f"[{sp['count']}]({url})"


def slug(text):
    return text.lower().replace(" / ", "-").replace(" ", "-")


def render(species, mine, notes):
    species = sorted(species, key=lambda s: (-s["count"], s["name"] or ""))
    seen = [s for s in species if s["id"] in mine]

    by_type = defaultdict(list)
    for s in species:
        by_type[s["type"]].append(s)
    # Same order in the summary and the sections: most species first.
    types = sorted(by_type, key=lambda t: (-len(by_type[t]), t))

    lines = [
        "# Species recorded in Co Cork\n",
        f"> Generated by `scripts/cork_species.py` from live iNaturalist data. Every observer's "
        f"Research Grade records in Co Cork (place {CORK_PLACE_ID}, land groups and seaweeds "
        f"excluded). ✅ marks species on `{USER_ID}`'s Irish underwater list.\n",
    ]
    lines += [f"> ⚠️ {n}" for n in notes]
    lines += [
        f"\n**{len(species)}** species · **{len(seen)}** observed by you · "
        f"**{len(species) - len(seen)}** not yet. Within each organism type, most records first.\n",
        "## By organism type\n",
        "| Organism type | Species | Observed | Not yet |",
        "|---|--:|--:|--:|",
    ]
    for t in types:
        n = len(by_type[t])
        k = sum(s["id"] in mine for s in by_type[t])
        lines.append(f"| [{t}](#{slug(t)}) | {n} | {k} | {n - k} |")
    for t in types:
        n = len(by_type[t])
        k = sum(s["id"] in mine for s in by_type[t])
        lines += [
            f"\n## {t}\n",
            f"{n} species, **{k}** observed by you.\n",
            "| Observed | Photo | Species | Observations in Co Cork |",
            "|:-:|---|---|--:|",
        ]
        for s in by_type[t]:
            lines.append(f"| {'✅' if s['id'] in mine else ''} | {thumb(s)} | {label(s)} | {obs_link(s)} |")
    return "\n".join(lines) + "\n"


def main():
    notes = []
    mine = set(species_table(underwater_entries(notes)))
    species = fetch_cork_species()
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(render(species, mine, notes))
    print(f"Saved {len(species)} species → {os.path.normpath(OUTPUT_FILE)}")
    for note in notes:
        print(f"WARNING: {note}")


if __name__ == "__main__":
    main()
