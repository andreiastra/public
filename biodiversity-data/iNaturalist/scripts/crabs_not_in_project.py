"""
List andreiastra's crab observations that are not in the iNaturalist project
"Crabs of the World" and write them to reports/crabs_not_in_project.md.

"Crab" means what the project accepts: its taxon rules (config.CRABS_PROJECT_TAXON_IDS),
which include hermit crabs (Anomura).  An observation is in the project when the
project's id is in its project_ids.  Observations are worldwide, not just Ireland.

Usage:
  ../.venv/bin/python scripts/crabs_not_in_project.py
"""
import os
import time

import requests

from config import (
    CRABS_PROJECT_ID,
    CRABS_PROJECT_TAXON_IDS,
    OBSERVATIONS_URL as BASE_URL,
    OUTPUT_DIR,
    PER_PAGE,
    THROTTLE_S,
    USER_ID,
)
from fetch_observations import cached
from generate_location_ratings import photo_md
from nudibranch_ireland import obs_url, site_of

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "crabs_not_in_project.md")
PROJECT_URL = "https://www.inaturalist.org/projects/crabs-of-the-world"


def crab_observations():
    """All the user's observations of the project's taxa."""
    observations = cached()
    if observations is not None:  # downloaded already (run_all.py): filter locally
        wanted = set(CRABS_PROJECT_TAXON_IDS)
        return [o for o in observations
                if wanted & set((o.get("taxon") or {}).get("ancestor_ids") or [])
                or (o.get("taxon") or {}).get("id") in wanted]
    print(f"Fetching crab observations for {USER_ID}…")
    all_obs, page = [], 1
    while True:
        r = requests.get(BASE_URL, params={
            "user_id":  USER_ID,
            "taxon_id": ",".join(map(str, CRABS_PROJECT_TAXON_IDS)),
            "per_page": PER_PAGE,
            "page":     page,
        }, timeout=30)
        r.raise_for_status()
        data    = r.json()
        results = data.get("results", [])
        all_obs.extend(results)
        print(f"  page {page}: {len(results)} obs  (running total: {len(all_obs)})")
        if not results or len(all_obs) >= data.get("total_results", 0):
            break
        page += 1
        time.sleep(THROTTLE_S)
    return all_obs


def not_in_project(crabs):
    return [o for o in crabs if CRABS_PROJECT_ID not in (o.get("project_ids") or [])]


def render(missing, total):
    missing = sorted(missing, key=lambda o: o.get("observed_on") or "", reverse=True)
    taxa = {(o.get("taxon") or {}).get("id") for o in missing}
    lines = [
        "# Crab observations not in the Crabs of the World project\n",
        f"> Generated by `scripts/crabs_not_in_project.py` "
        f"from live iNaturalist data for `{USER_ID}`.\n",
        f"Project: [Crabs of the World]({PROJECT_URL}). It accepts Brachyura, Anomura "
        f"(so hermit crabs count), Macrophthalmidae and Ocypodoidea. Worldwide, not just Ireland.\n",
        f"**{len(missing)}** of **{total}** crab observations are not in the project "
        f"(**{len(taxa)}** taxa). Newest first.\n",
    ]
    if not missing:
        lines.append("Nothing to add: every crab observation is already in the project.")
        return "\n".join(lines) + "\n"
    lines += [
        "| Photo | Date | Species | Place | Grade |",
        "|---|---|---|---|---|",
    ]
    for obs in missing:
        taxon  = obs.get("taxon") or {}
        common = taxon.get("preferred_common_name") or taxon.get("name") or "Unknown"
        sci    = taxon.get("name") or ""
        label  = f"[{common}]({obs_url(obs)})"
        if sci and sci != common:
            label += f" (*{sci}*)"
        grade = "Research" if obs.get("quality_grade") == "research" else "Needs ID"
        lines.append(
            f"| {photo_md(obs)} | {obs.get('observed_on') or '—'} | {label} "
            f"| {site_of(obs)} | {grade} |"
        )
    return "\n".join(lines) + "\n"


def main():
    """Write the report. Returns a warning string if crabs are missing from the project, else None."""
    crabs = crab_observations()
    missing = not_in_project(crabs)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(render(missing, len(crabs)))
    print(f"Saved {len(missing)} of {len(crabs)} crab observations → {os.path.normpath(OUTPUT_FILE)}")
    if missing:
        warning = (f"{len(missing)} crab observation(s) are not in the Crabs of the World project. "
                   f"Add them, then rerun. See reports/crabs_not_in_project.md")
        print(f"⚠️  {warning}")
        return warning
    print("All crab observations are in the project.")
    return None


if __name__ == "__main__":
    main()
