"""
Write reports/rarity_by_site_ireland.md: where in Ireland andreiastra found the
rarest underwater species, and which sites are worth going back to.

Combines the per-taxon rarity of rarity_underwater_ireland.py (distinct observers
with a verifiable record anywhere in Ireland, same ratings, same
scripts/.cache/taxon_counts.json cache) with the site each species was found at.

Only Research Grade, species-rank observations count, so the ratings agree with
reports/rarity_underwater_ireland.md. Observations with an obscured location can't
be placed on a site (see README "Obscured locations"), so they appear in the
rarest-finds table with the site "Obscured location" and are left out of the
per-site table.

Usage:
  ../.venv/bin/python scripts/rarity_by_site_ireland.py [--refresh]
"""
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(__file__))
from config import IRELAND_PLACE_ID, OUTPUT_DIR, USER_ID
from generate_location_ratings import photo_md
from rarity_underwater_ireland import (
    DEFAULT_RATING,
    RATINGS,
    cached_counts,
    load_counts_cache,
    rating,
    save_counts_cache,
)
from underwater_stats import site_label, species_table, taxon_link, underwater_entries

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "rarity_by_site_ireland.md")
TIERS = [label for _, label in RATINGS] + [DEFAULT_RATING]
RARE_TIERS = {"Unique", "Very rare", "Rare"}  # the finds that make a site worth revisiting
TOP_FINDS = 30


def research_species(entries):
    """Species table restricted to Research Grade observations."""
    return species_table([(s, o) for s, o in entries if o.get("quality_grade") == "research"])


def add_counts(table, refresh):
    """Add 'observers' and 'total' (Ireland-wide, verifiable) to every species."""
    cache = load_counts_cache()
    try:
        for i, (tid, info) in enumerate(table.items(), 1):
            (info["observers"], info["total"]), _ = cached_counts(cache, tid, IRELAND_PLACE_ID, refresh)
            if i % 20 == 0:
                print(f"  {i}/{len(table)}")
    finally:
        save_counts_cache(cache)


def site_stats(table):
    """Return {site: {"species": {tid}, tier: count, ...}} for observations placed on a site."""
    stats = defaultdict(lambda: {"species": set(), **{t: 0 for t in TIERS}})
    for tid, info in table.items():
        tier = rating(info["observers"])
        for site in {s for s, _ in info["entries"] if s}:
            stats[site]["species"].add(tid)
            stats[site][tier] += 1
    return stats


def render(table, notes):
    stats = site_stats(table)
    # Rarest first; ties go to fewer Ireland-wide observations, then name.
    ranked = sorted(table.items(), key=lambda kv: (kv[1]["observers"], kv[1]["total"],
                                                   kv[1]["taxon"].get("name") or ""))
    rare = [(tid, i) for tid, i in ranked if rating(i["observers"]) in RARE_TIERS]

    lines = [
        "# Rarity by site: where the rare finds are\n",
        f"> Generated by `scripts/rarity_by_site_ireland.py` "
        f"from live iNaturalist data for `{USER_ID}`. Research Grade species only. "
        f"Rarity is the number of distinct observers with a verifiable record anywhere in "
        f"Ireland, as in [`rarity_underwater_ireland.md`](rarity_underwater_ireland.md).\n",
    ]
    lines += [f"> ⚠️ {n}" for n in notes]
    lines += [
        f"\n**{len(table)}** Research Grade species · **{len(rare)}** rated Rare or rarer "
        f"(20 or fewer observers in Ireland) · **{len(stats)}** sites\n",
        "## Sites ranked by rare finds\n",
        "Sites with the most Rare, Very rare and Unique species come first. A site that "
        "gives many rare species in few dives is the best one to go back to.\n",
        "| Site | Species | " + " | ".join(TIERS) + " | Rare or rarer | Rarest find |",
        "|---|--:|" + "--:|" * len(TIERS) + "--:|---|",
    ]

    def rare_count(site):
        return sum(stats[site][t] for t in RARE_TIERS)

    def rarest_at(site):
        here = [(tid, table[tid]) for tid in stats[site]["species"]]
        return min(here, key=lambda kv: (kv[1]["observers"], kv[1]["total"]))

    for site in sorted(stats, key=lambda s: (-rare_count(s), -len(stats[s]["species"]), s)):
        tid, info = rarest_at(site)
        lines.append(
            f"| {site} | {len(stats[site]['species'])} | "
            + " | ".join(str(stats[site][t]) for t in TIERS)
            + f" | **{rare_count(site)}** | {taxon_link(info['taxon'])} "
            f"({info['observers']:,} observer{'' if info['observers'] == 1 else 's'}) |"
        )

    lines += [
        f"\n## The {min(TOP_FINDS, len(rare))} rarest finds\n",
        "| # | Photo | Species | Rating | Observers in Ireland | Sites | Date first seen |",
        "|--:|---|---|---|--:|---|---|",
    ]
    for n, (tid, info) in enumerate(rare[:TOP_FINDS], 1):
        first_site, first_obs = info["entries"][0]
        sites = sorted({site_label(s) for s, _ in info["entries"]})
        lines.append(
            f"| {n} | {photo_md(first_obs)} | {taxon_link(info['taxon'])} "
            f"| {rating(info['observers'])} | {info['observers']:,} | {', '.join(sites)} "
            f"| {first_obs.get('observed_on') or '—'} |"
        )
    return "\n".join(lines) + "\n"


def main():
    notes = []
    table = research_species(underwater_entries(notes))
    print(f"{len(table)} Research Grade species. Getting Ireland-wide counts…")
    add_counts(table, "--refresh" in sys.argv)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(render(table, notes))
    print(f"Saved {len(table)} species → {os.path.normpath(OUTPUT_FILE)}")
    for note in notes:
        print(f"WARNING: {note}")


if __name__ == "__main__":
    main()
