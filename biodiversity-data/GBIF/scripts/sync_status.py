"""
Write reports/sync_status.md: which of andreiastra's research-grade iNaturalist
observations are on GBIF, and which are not yet.

Both sides are downloaded live: the GBIF occurrences from the iNaturalist dataset
and the research-grade observations from iNaturalist. They are matched on the
iNaturalist observation id, which GBIF keeps in occurrenceID
(https://www.inaturalist.org/observations/<id>).

An observation that is research grade on iNaturalist but absent from GBIF is
usually just waiting for GBIF's next sync (it lags by days). GBIF has no
"became research grade" date, so the report shows iNaturalist's updated_at, which
is only an upper bound for that date.

Usage:
  ../.venv/bin/python scripts/sync_status.py
"""
import os
import re
import sys
import time

import requests

sys.path.insert(0, os.path.dirname(__file__))
from config import (
    INATURALIST_OBSERVATIONS_URL,
    INATURALIST_PER_PAGE,
    INATURALIST_USER_ID,
    OUTPUT_DIR,
    THROTTLE_S,
)
from fetch_occurrences import cached, refresh

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "sync_status.md")
OBS_URL = "https://www.inaturalist.org/observations/{}"
GBIF_URL = "https://www.gbif.org/occurrence/{}"


def fetch_research_grade():
    """All of the user's research-grade observations from the iNaturalist API."""
    print(f"Fetching research-grade observations for '{INATURALIST_USER_ID}' from iNaturalist…")
    observations, page = [], 1
    while True:
        r = requests.get(INATURALIST_OBSERVATIONS_URL, params={
            "user_id":       INATURALIST_USER_ID,
            "quality_grade": "research",
            "per_page":      INATURALIST_PER_PAGE,
            "page":          page,
        }, timeout=30)
        r.raise_for_status()
        data = r.json()
        observations.extend(data.get("results", []))
        print(f"  page {page}: {len(data.get('results', []))} obs  (running total: {len(observations)})")
        if len(observations) >= data.get("total_results", 0):
            return observations
        page += 1
        time.sleep(THROTTLE_S)


def observation_id(occurrence):
    """The iNaturalist observation id behind a GBIF occurrence, or None."""
    m = re.search(r"/observations/(\d+)$", occurrence.get("occurrenceID") or "")
    return int(m.group(1)) if m else None


def name(obs):
    taxon = obs.get("taxon") or {}
    common = taxon.get("preferred_common_name")
    latin = taxon.get("name") or "—"
    return f"{common} (*{latin}*)" if common else f"*{latin}*"


def render(observations, occurrences):
    on_gbif = {observation_id(o): o for o in occurrences}
    on_gbif.pop(None, None)
    research_ids = {o["id"] for o in observations}

    missing = sorted((o for o in observations if o["id"] not in on_gbif),
                     key=lambda o: o.get("updated_at") or "", reverse=True)
    synced = len(observations) - len(missing)
    extra = sorted(i for i in on_gbif if i not in research_ids)
    last_sync = max((o.get("lastInterpreted") or "" for o in occurrences), default="")[:10] or "—"

    lines = [
        "# GBIF sync status: research-grade observations not yet on GBIF\n",
        f"> Generated by `scripts/sync_status.py` from live iNaturalist and GBIF data "
        f"for `{INATURALIST_USER_ID}`. Matched on the iNaturalist observation id in GBIF's `occurrenceID`.\n",
        f"**{synced}** of **{len(observations)}** research-grade observations are on GBIF "
        f"· **{len(missing)}** are not yet. Latest GBIF interpretation of any of your records: {last_sync}.\n",
        "GBIF re-reads iNaturalist every few days, so an observation that turned research grade "
        "recently is normally just waiting for the next sync.\n",
    ]

    lines += ["## Research grade on iNaturalist, not on GBIF\n"]
    if missing:
        lines += ["| Observation | Species | Observed | Updated on iNaturalist |", "|---|---|---|---|"]
        for o in missing:
            lines.append(
                f"| [{o['id']}]({OBS_URL.format(o['id'])}) | {name(o)} "
                f"| {o.get('observed_on') or '—'} | {(o.get('updated_at') or '—')[:10]} |"
            )
    else:
        lines.append("None. Everything research grade is on GBIF.")

    lines += ["\n## On GBIF, no longer research grade on iNaturalist\n"]
    if extra:
        lines += ["| Observation | GBIF occurrence |", "|---|---|"]
        for i in extra:
            lines.append(f"| [{i}]({OBS_URL.format(i)}) | [{on_gbif[i]['key']}]({GBIF_URL.format(on_gbif[i]['key'])}) |")
        lines.append("\nThe identification changed after GBIF's last sync; GBIF drops these on its next sync.")
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n", len(missing), len(extra)


def main():
    occurrences = cached()
    if occurrences is None:
        occurrences = refresh()
    observations = fetch_research_grade()
    text, missing, extra = render(observations, occurrences)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Saved sync status ({missing} not yet on GBIF, {extra} to be dropped) → {os.path.normpath(OUTPUT_FILE)}")


if __name__ == "__main__":
    main()
