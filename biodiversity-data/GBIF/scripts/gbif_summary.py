"""
Write reports/gbif_summary.md: what andreiastra's records on GBIF look like.

Counts by country, organism class, year and the issues GBIF raised, plus how many
species the records cover. A second count and table cover only the underwater
(marine) records, using the check in marine.py. Uses only the GBIF data (no
iNaturalist calls). The marine flags are fetched once per species and cached.

Usage:
  ../.venv/bin/python scripts/gbif_summary.py
"""
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(__file__))
from config import OUTPUT_DIR, RECORDED_BY
from fetch_occurrences import cached, refresh
from marine import is_underwater, marine_flags

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "gbif_summary.md")

# Meaning of the issues that GBIF adds to iNaturalist records.
ISSUE_NOTES = {
    "COORDINATE_ROUNDED": "GBIF rounded the coordinates to 6 decimal places. Harmless.",
    "CONTINENT_DERIVED_FROM_COORDINATES": "GBIF worked out the continent from the coordinates. Harmless.",
    "COUNTRY_DERIVED_FROM_COORDINATES": "GBIF worked out the country from the coordinates. Harmless.",
    "TAXON_ID_NOT_FOUND": "The iNaturalist taxon id has no match in GBIF; the name still resolved. Harmless.",
    "TAXON_MATCH_HIGHERRANK": "The name matched GBIF only at a higher rank (the record is identified to genus, not species).",
}


def group(o):
    """Class, or the order or phylum when GBIF's backbone has no class (e.g. ray-finned fish)."""
    return o.get("class") or o.get("order") or o.get("phylum") or o.get("kingdom") or "—"


def table(title, counter, header):
    lines = [f"\n## {title}\n", f"| {header} | Records |", "|---|--:|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], str(kv[0])))]
    return lines


def render(occurrences, flags):
    """`flags` maps each speciesKey (a string) to its marine flag."""
    countries = Counter(o.get("country") or o.get("countryCode") or "—" for o in occurrences)
    classes = Counter(group(o) for o in occurrences)
    underwater = [o for o in occurrences
                  if o.get("speciesKey") and is_underwater(flags[str(o["speciesKey"])], group(o))]
    underwater_species = {o["speciesKey"] for o in underwater}
    years = Counter(str(o.get("year") or "—") for o in occurrences)
    species = {o.get("speciesKey") for o in occurrences if o.get("speciesKey")}
    issues = Counter(i for o in occurrences for i in o.get("issues", []))

    lines = [
        "# GBIF summary\n",
        f"> Generated by `scripts/gbif_summary.py` from live GBIF data for records recorded by "
        f"`{RECORDED_BY}` in the iNaturalist research-grade dataset.\n",
        f"**{len(occurrences)}** occurrences · **{len(species)}** species. "
        f"Underwater: **{len(underwater)}** occurrences · **{len(underwater_species)}** species.",
    ]
    lines += table("By country", countries, "Country")
    lines += table("By organism group", classes, "Group")
    lines.append("\nThe group is the GBIF class. Where the backbone has no class (ray-finned fish, flatworms) it is the order, "
                 "or the phylum if there is no order either.")
    lines += table("Underwater records by group", Counter(group(o) for o in underwater), "Group")
    lines.append("\nUnderwater means a GBIF species profile (WoRMS or Catalogue of Life) marks the species as marine, "
                 "leaving out birds and flowering plants (seabirds and coastal plants). Records identified only above "
                 "species are not counted. Seaweeds with no marine value in GBIF are left out too.")
    lines += table("By year observed", years, "Year")

    lines += ["\n## Issues GBIF raised\n", "| Issue | Records | Meaning |", "|---|--:|---|"]
    for issue, n in sorted(issues.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{issue}` | {n} | {ISSUE_NOTES.get(issue, 'See the GBIF issue vocabulary.')} |")
    return "\n".join(lines) + "\n", len(species)


def main():
    occurrences = cached()
    if occurrences is None:
        occurrences = refresh()
    flags = marine_flags(sorted({str(o["speciesKey"]) for o in occurrences if o.get("speciesKey")}))
    text, species = render(occurrences, flags)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Saved {len(occurrences)} occurrences, {species} species → {os.path.normpath(OUTPUT_FILE)}")


if __name__ == "__main__":
    main()
