"""
Write reports/cork_underwater.md: an overview of the underwater (marine) species
that anyone has recorded in West Cork, according to GBIF, with the records behind
them.

Like lough_hyne_species.py this uses every dataset on GBIF, not only andreiastra's
records, and the same marine filter and copy removal. The area is the GADM level 2
boundary of West Cork (WEST_CORK_GADM_GID in config.py), not a polygon. The filters:

  1. inside West Cork (gadmGid = WEST_CORK_GADM_GID)
  2. occurrenceStatus = PRESENT (absence records are dropped)
  3. mediaType = StillImage (the record has a photo)
  4. identified to species
  5. marine species (see lough_hyne_species.py), without the groups in NOT_UNDERWATER
  6. copies removed (see without_copies)

Species profiles are shared with lough_hyne_species.py through its cache, so
species already profiled there are not fetched again.

Usage:
  ../.venv/bin/python scripts/cork_underwater.py
"""
import os
import sys
import time
from collections import Counter

sys.path.insert(0, os.path.dirname(__file__))
from config import OCCURRENCE_SEARCH_URL, OUTPUT_DIR, PAGE_SIZE, RECORDED_BY, THROTTLE_S, WEST_CORK_GADM_GID
import lough_hyne_species as lh

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "cork_underwater.md")
TOP_SPECIES = 25  # rows in the "most photographed" table


def fetch_occurrences():
    """Present occurrences with a photo inside West Cork, from every dataset."""
    params = {"gadmGid": WEST_CORK_GADM_GID, "occurrenceStatus": "PRESENT",
              "mediaType": "StillImage", "limit": PAGE_SIZE}
    results, offset = [], 0
    while True:
        data = lh.get(OCCURRENCE_SEARCH_URL, **params, offset=offset)
        results.extend(data["results"])
        if data["endOfRecords"]:
            return results
        offset += PAGE_SIZE
        time.sleep(THROTTLE_S)


def render(occurrences, profiles):
    """Markdown overview. `occurrences` all have a photo and lie in West Cork."""
    keys = {str(o["speciesKey"]) for o in occurrences if o.get("speciesKey")}
    marine = {k for k, p in profiles.items() if p["marine"] and p["group"] not in lh.NOT_UNDERWATER}
    records = [o for o in occurrences if str(o.get("speciesKey")) in marine]
    records, copies = lh.without_copies(records)

    by_species = {}
    for o in records:
        by_species.setdefault(str(o["speciesKey"]), []).append(o)
    mine = sum(lh.plain(o.get("recordedBy")) == lh.plain(RECORDED_BY) for o in records)
    datasets = Counter(o.get("datasetName") or o.get("datasetKey") for o in records)
    years = Counter((o.get("year") or 0) for o in records if o.get("year"))

    def label(k):
        p = profiles[k]
        return p["common"] or f"*{p['name']}*"

    grouped = {}
    for k, recs in by_species.items():
        grouped.setdefault(lh.group_of(recs[0]), []).append(k)
    ordered = sorted(grouped.items(), key=lambda kv: (kv[0] == lh.OTHER, -len(kv[1]), kv[0]))

    top = sorted(by_species.items(), key=lambda kv: (-len(kv[1]), label(kv[0]).strip("*").lower()))[:TOP_SPECIES]

    lines = [
        "# Underwater species in West Cork on GBIF\n",
        "> Generated by `scripts/cork_underwater.py` from live GBIF data. Every recorder and dataset, "
        "not only `andreiastra`.\n",
        f"**{len(by_species)}** marine species from **{len(records)}** photos in West Cork. "
        f"{len(occurrences)} present occurrences with a photo lie in the county, covering {len(keys)} species "
        f"of any habitat. {copies} copies of iNaturalist records were left out.\n",
        "## Filters applied\n",
        f"1. Inside West Cork, GADM level 2 `{WEST_CORK_GADM_GID}`: `gadmGid={WEST_CORK_GADM_GID}`",
        "2. Occurrence is present, not an absence record: `occurrenceStatus=PRESENT`",
        "3. The record has a photo: `mediaType=StillImage`",
        "4. Identified to species: has a `speciesKey`",
        f"5. Marine species, leaving out {' and '.join(sorted(lh.NOT_UNDERWATER))} (seabirds and coastal plants): "
        "a GBIF species profile (WoRMS or Catalogue of Life) marks it as marine",
        "6. No copies: a record from another dataset (such as Explore Your Shore) is left out when an iNaturalist "
        "record has the same species, recorder and date, because it republishes the same photo\n",
        "The filters can be repeated on [gbif.org/occurrence/search](https://www.gbif.org/occurrence/search) "
        f"(GADM, `{WEST_CORK_GADM_GID}`; Occurrence status, Present; Media type, Still image). "
        "The website can't filter by marine species, so filters 4 to 6 are applied by the script.\n",
        "## Species by group\n",
        f"**{len(by_species)}** species in {len(grouped)} groups.\n",
        "| Group | Species | Photos |",
        "|---|--:|--:|",
    ]
    lines += [f"| {group} | {len(ks)} | {sum(len(by_species[k]) for k in ks)} |" for group, ks in ordered]

    lines += ["\n## Most photographed species\n",
              f"The {TOP_SPECIES} species with the most photos.\n",
              "| Common name | Group | Photos |", "|---|---|--:|"]
    lines += [f"| {label(k)} | {group_name} | {len(recs)} |"
              for k, recs in top
              for group_name in [lh.group_of(recs[0])]]

    lines += ["\n## Photos by year\n", "| Year | Photos |", "|---|--:|"]
    lines += [f"| {y} | {n} |" for y, n in sorted(years.items(), reverse=True)]

    lines += ["\n## Datasets\n", "| Dataset | Photos |", "|---|--:|"]
    lines += [f"| {name} | {n} |" for name, n in datasets.most_common()]

    lines.append(
        "\nThe marine flag comes from taxon profiles, so a marine species seen on the shore or from a boat "
        "counts too, and a freshwater or terrestrial species never appears. A species with no marine value "
        "in its GBIF profile (some seaweeds) is left out. Records carry a coordinate uncertainty, so some may "
        "come from the sea or land just outside the county. For the photos themselves, see "
        "[`lough_hyne_species.md`](lough_hyne_species.md) for the Lough Hyne records.")
    return "\n".join(lines) + "\n", len(records), len(by_species)


def main():
    occurrences = fetch_occurrences()
    profiles = lh.profiles_for(sorted({str(o["speciesKey"]) for o in occurrences if o.get("speciesKey")}))
    text, records, species = render(occurrences, profiles)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Saved {species} marine species from {records} photos → {os.path.normpath(OUTPUT_FILE)}")


if __name__ == "__main__":
    main()
