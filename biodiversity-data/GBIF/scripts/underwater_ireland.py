"""
Write reports/underwater_ireland.md: andreiastra's underwater observations in
Ireland, and which of them are on GBIF.

GBIF has no habitat field, so "underwater" comes from iNaturalist: the
observations that iNaturalist/scripts/underwater_ireland.py puts on a dive site
(the same data set as iNaturalist/reports/underwater_ireland.md, any grade, plus
the obscured ones). Each is matched to its GBIF occurrence on the iNaturalist
observation id, which GBIF keeps in occurrenceID.

Both folders have a config.py, so the iNaturalist code runs in a subprocess
rather than being imported. It downloads the observations from iNaturalist.

Usage:
  ../.venv/bin/python scripts/underwater_ireland.py
"""
import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(__file__))
from config import INATURALIST_SCRIPTS_DIR, INATURALIST_USER_ID, OUTPUT_DIR
from fetch_occurrences import cached, refresh
from gbif_summary import group

OUTPUT_FILE = os.path.join(OUTPUT_DIR, "underwater_ireland.md")
OBS_URL = "https://www.inaturalist.org/observations/{}"
OBSCURED = "Obscured location"

# Runs inside iNaturalist/scripts. Progress goes to stderr, the result to stdout.
_CHILD = """
import contextlib, json, sys
with contextlib.redirect_stdout(sys.stderr):
    from underwater_ireland import underwater_observations
    site_obs, obscured = underwater_observations([])
rows = [(site, o) for site, obs in site_obs.items() for o in obs] + [(None, o) for o in obscured]
print(json.dumps([{
    "id": o["id"],
    "site": site,
    "grade": o.get("quality_grade"),
    "license": o.get("license_code"),
    "date": o.get("observed_on"),
    "common": (o.get("taxon") or {}).get("preferred_common_name"),
    "latin": (o.get("taxon") or {}).get("name"),
} for site, o in rows]))
"""


def fetch_underwater():
    """The user's underwater observations in Ireland, from the iNaturalist scripts."""
    out = subprocess.run([sys.executable, "-c", _CHILD], cwd=INATURALIST_SCRIPTS_DIR,
                         check=True, stdout=subprocess.PIPE, text=True).stdout
    return json.loads(out)


def observation_id(occurrence):
    m = re.search(r"/observations/(\d+)$", occurrence.get("occurrenceID") or "")
    return int(m.group(1)) if m else None


def name(o):
    common, latin = o.get("common"), o.get("latin") or "—"
    return f"{common} (*{latin}*)" if common else f"*{latin}*"


def render(underwater, occurrences):
    by_id = {observation_id(o): o for o in occurrences}
    by_id.pop(None, None)
    matched = [(u, by_id[u["id"]]) for u in underwater if u["id"] in by_id]
    missing = [u for u in underwater if u["id"] not in by_id]
    needs_id = [u for u in missing if u["grade"] != "research"]
    waiting = [u for u in missing if u["grade"] == "research"]
    underwater_ids = {u["id"] for u in underwater}
    other_irish = sum(1 for o in occurrences if o.get("countryCode") == "IE" and observation_id(o) not in underwater_ids)

    lines = [
        "# Underwater observations in Ireland on GBIF\n",
        f"> Generated by `scripts/underwater_ireland.py` from live iNaturalist and GBIF data for "
        f"`{INATURALIST_USER_ID}`. \"Underwater\" is the data set of "
        f"[`iNaturalist/reports/underwater_ireland.md`](../../iNaturalist/reports/underwater_ireland.md): "
        f"observations on a dive site, plus obscured ones. Matched on the iNaturalist observation id.\n",
        f"**{len(underwater)}** underwater observations on iNaturalist (any grade) "
        f"· **{len(matched)}** are on GBIF · **{len(missing)}** are not.\n",
        "| | Observations |",
        "|---|--:|",
        f"| Underwater on iNaturalist | {len(underwater)} |",
        f"| On GBIF | {len(matched)} |",
        f"| Not on GBIF: not research grade (Needs ID or casual) | {len(needs_id)} |",
        f"| Not on GBIF: research grade, waiting for GBIF's next sync | {len(waiting)} |",
        f"| Other Irish records on GBIF (birds, land and other non-dive records) | {other_irish} |",
    ]

    groups = Counter(group(o) for _, o in matched)
    lines += ["\n## By organism group\n", "| Group | Records |", "|---|--:|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(groups.items(), key=lambda kv: (-kv[1], kv[0]))]
    lines.append("\nThe group is the GBIF class, or the order or phylum where the backbone has no class.")

    sites = defaultdict(lambda: [0, 0])
    for u in underwater:
        row = sites[u["site"] or OBSCURED]
        row[0] += 1
        row[1] += u["id"] in by_id
    lines += ["\n## By site\n", "| Site | On iNaturalist | On GBIF |", "|---|--:|--:|"]
    for site, (total, on_gbif) in sorted(sites.items(), key=lambda kv: (-kv[1][0], kv[0])):
        lines.append(f"| {site} | {total} | {on_gbif} |")

    years = Counter((u["date"] or "—")[:4] for u, _ in matched)
    lines += ["\n## By year observed\n", "| Year | Records |", "|---|--:|"]
    lines += [f"| {y} | {n} |" for y, n in sorted(years.items(), reverse=True)]

    lines += ["\n## Research grade on iNaturalist, not on GBIF\n"]
    if waiting:
        lines += ["| Observation | Species | Site | Observed | License |", "|---|---|---|---|---|"]
        for u in sorted(waiting, key=lambda u: u["date"] or "", reverse=True):
            lines.append(f"| [{u['id']}]({OBS_URL.format(u['id'])}) | {name(u)} | {u['site'] or OBSCURED} "
                         f"| {u['date'] or '—'} | {u['license'] or 'none'} |")
        lines.append("\nGBIF publishes only openly licensed observations. A record with a licence is normally "
                     "waiting for the next sync; one with no licence will not arrive.")
    else:
        lines.append("None. Every research-grade underwater observation is on GBIF.")
    return "\n".join(lines) + "\n", len(underwater), len(matched)


def main():
    occurrences = cached()
    if occurrences is None:
        occurrences = refresh()
    underwater = fetch_underwater()
    text, total, matched = render(underwater, occurrences)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Saved {matched} of {total} underwater observations on GBIF → {os.path.normpath(OUTPUT_FILE)}")


if __name__ == "__main__":
    main()
